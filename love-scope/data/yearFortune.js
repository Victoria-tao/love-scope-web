// ============ 推算某年干支 ============
function getGanZhi(year) {
  const g = ((year - 4) % 10 + 10) % 10;
  const z = ((year - 4) % 12 + 12) % 12;
  return {
    year: year,
    gan: TIAN_GAN[g],
    zhi: DI_ZHI[z],
    animal: ZHI_ANIMAL[z],
    ganFive: GAN_FIVE[g],
    zhiFive: ZHI_FIVE[z],
    ganYin: g % 2 === 0,
    zhiYin: ZHI_YIN[z],
    ganZhi: TIAN_GAN[g] + DI_ZHI[z]
  };
}

// ============ 年度年度情感状态 ============
function getYearFortune(year) {
  const gz = getGanZhi(year);
  const zl = ZHI_LOVE[gz.zhi === '子' ? 0 : DI_ZHI.indexOf(gz.zhi)];
  return {
    year: gz.year,
    ganZhi: gz.ganZhi,
    animal: gz.animal,
    ganFive: gz.ganFive,
    zhiFive: gz.zhiFive,
    theme: zl.theme,
    tao: zl.tao,
    star: zl.star,
    summary: zl.summary,
    ganNote: GAN_NOTE[gz.ganFive]
  };
}

// ============ 五行关系（个人五行 vs 年度地支五行） ============
function fiveRelation(a, b) {
  if (a === b) return 'same';
  if (SHENG[a] === b) return 'a_sheng_b';   // a 生 b
  if (SHENG[b] === a) return 'b_sheng_a';   // b 生 a
  if (KE[a] === b) return 'a_ke_b';         // a 克 b
  return 'b_ke_a';                          // b 克 a
}

